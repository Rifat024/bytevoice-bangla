def build_clinic_facts_bn(catalog: ClinicCatalog) -> str:
    clinic = catalog.clinic
    weekday_names = ("রবি", "সোম", "মঙ্গল", "বুধ", "বৃহস্পতি", "শুক্র", "শনি")
    doctor_lines = []
    for doctor in catalog.doctors:
        if not doctor.is_active:
            continue
        chambers = ", ".join(
            f"{weekday_names[schedule.weekday]} {schedule.start_time.strftime('%H:%M')}–{schedule.end_time.strftime('%H:%M')}"
            for schedule in sorted(
                (item for item in catalog.schedules if item.doctor_id == doctor.id),
                key=lambda item: (item.weekday + 1) % 7,
            )
        )
        services = ", ".join(
            service.name_bn
            for service in catalog.services
            if service.id in catalog.doctor_service_ids.get(doctor.id, set())
        )
        specialty = f" ({doctor.specialty_bn})" if doctor.specialty_bn else ""
        doctor_lines.append(f"- {doctor.full_name_bn}{specialty}; সেবা: {services}; চেম্বার: {chambers}")
    service_lines = [
        f"- {service.name_bn} [service_code={service.code}]: {service.fee_bdt} টাকা{' থেকে শুরু' if service.fee_is_starting_price else ''}, "
        f"প্রায় {service.duration_min} মিনিট"
        + (f"; প্রস্তুতি: {service.prep_notes_bn}" if service.prep_notes_bn else "")
        for service in catalog.services
    ]
    return "\n".join(
        [
            f"ক্লিনিক: {clinic.name_bn} ({clinic.name_en}), {clinic.address_bn}।",
            f"ক্লিনিকের ফ্রন্ট ডেস্ক নম্বর: {clinic.phone}। (ডাক্তারদের ব্যক্তিগত নম্বর দেওয়া হয় না।)",
            "খোলা: শনিবার থেকে বৃহস্পতিবার, সকাল ১০টা থেকে রাত ৯টা। শুক্রবার বন্ধ।",
            "ডাক্তার:",
            *doctor_lines,
            "সেবা ও ফি:",
            *service_lines,
            "সাধারণ: আগের ডেন্টাল এক্স-রে বা প্রেসক্রিপশন থাকলে সাথে আনবেন, সময়ের ১০ মিনিট আগে আসবেন।",
        ]
    )


def build_instructions(now: datetime | None = None, catalog: ClinicCatalog | None = None) -> str:
    current = (now or datetime.now(CLINIC_TIMEZONE)).astimezone(CLINIC_TIMEZONE)
    weekday_bn = BANGLA_WEEKDAY_NAMES[current.weekday()]
    today_bn = f"{weekday_bn}, {current.strftime('%d-%m-%Y')}".translate(BANGLA_DIGIT_TRANSLATION)
    time_bn = current.strftime("%H:%M").translate(BANGLA_DIGIT_TRANSLATION)
    clinic_facts = build_clinic_facts_bn(catalog) if catalog else CLINIC_FACTS_BN
    return PERSONA_TEMPLATE.format(today_bn=today_bn, time_bn=time_bn, clinic_facts=clinic_facts)
