def build_instructions(now: datetime | None = None) -> str:
    current = (now or datetime.now(CLINIC_TIMEZONE)).astimezone(CLINIC_TIMEZONE)
    weekday_bn = BANGLA_WEEKDAY_NAMES[current.weekday()]
    today_bn = f"{weekday_bn}, {current.strftime('%d-%m-%Y')}".translate(BANGLA_DIGIT_TRANSLATION)
    time_bn = current.strftime("%H:%M").translate(BANGLA_DIGIT_TRANSLATION)
    return PERSONA_TEMPLATE.format(today_bn=today_bn, time_bn=time_bn, clinic_facts=CLINIC_FACTS_BN)
